-- SpendWise AI — money model (wallets + transactions)
--
-- Run once in the Supabase SQL editor. This migration is additive and
-- non-destructive: it never drops or rewrites `public.expenses`.
--
-- What it does:
--   1. Creates `wallets` (where money lives) and `transactions`
--      (income, expense, and transfer movements).
--   2. Enables row-level security so every row is scoped to auth.uid().
--   3. Creates one "Main account" wallet per user that already has expenses.
--   4. Backfills every existing expense into `transactions`, keyed by
--      `legacy_expense_id` so re-running this file is safe.
--
-- After running it, the app can move off `expenses` without losing history.

begin;

-- ---------------------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Wallets
-- ---------------------------------------------------------------------------

create table if not exists public.wallets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 60),
  type text not null default 'bank'
    check (type in ('bank', 'cash', 'credit', 'wallet', 'investment')),
  currency text not null default 'INR'
    check (currency in ('INR', 'USD', 'EUR', 'GBP', 'AED', 'SGD')),
  opening_balance numeric(14, 2) not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists wallets_user_name_key
  on public.wallets (user_id, lower(name));

create index if not exists wallets_user_active_idx
  on public.wallets (user_id, is_active);

drop trigger if exists wallets_set_updated_at on public.wallets;
create trigger wallets_set_updated_at
  before update on public.wallets
  for each row execute function public.set_updated_at();

alter table public.wallets enable row level security;

drop policy if exists "wallets_select_own" on public.wallets;
create policy "wallets_select_own" on public.wallets
  for select using (auth.uid() = user_id);

drop policy if exists "wallets_insert_own" on public.wallets;
create policy "wallets_insert_own" on public.wallets
  for insert with check (auth.uid() = user_id);

drop policy if exists "wallets_update_own" on public.wallets;
create policy "wallets_update_own" on public.wallets
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "wallets_delete_own" on public.wallets;
create policy "wallets_delete_own" on public.wallets
  for delete using (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- Transactions
-- ---------------------------------------------------------------------------
-- `expense`  : money leaves `wallet_id`.
-- `income`   : money enters `wallet_id`.
-- `transfer` : money moves from `wallet_id` to `transfer_wallet_id`.
-- `legacy_expense_id` links a backfilled row to its original expense so the
-- backfill can be re-run without creating duplicates.

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  type text not null default 'expense'
    check (type in ('income', 'expense', 'transfer')),
  name text not null check (length(btrim(name)) between 1 and 120),
  amount numeric(14, 2) not null check (amount > 0),
  category text not null default 'Other',
  category_id bigint references public.categories (id) on delete set null,
  description text not null default '',
  date date not null,
  wallet_id bigint references public.wallets (id) on delete set null,
  transfer_wallet_id bigint references public.wallets (id) on delete set null,
  recurring_expense_id bigint
    references public.recurring_expenses (id) on delete set null,
  legacy_expense_id bigint unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transactions_transfer_target check (
    (type = 'transfer' and transfer_wallet_id is not null)
    or (type <> 'transfer' and transfer_wallet_id is null)
  )
);

create index if not exists transactions_user_date_idx
  on public.transactions (user_id, date desc);

create index if not exists transactions_user_wallet_idx
  on public.transactions (user_id, wallet_id);

create index if not exists transactions_user_type_idx
  on public.transactions (user_id, type);

create index if not exists transactions_user_category_idx
  on public.transactions (user_id, category);

drop trigger if exists transactions_set_updated_at on public.transactions;
create trigger transactions_set_updated_at
  before update on public.transactions
  for each row execute function public.set_updated_at();

alter table public.transactions enable row level security;

drop policy if exists "transactions_select_own" on public.transactions;
create policy "transactions_select_own" on public.transactions
  for select using (auth.uid() = user_id);

drop policy if exists "transactions_insert_own" on public.transactions;
create policy "transactions_insert_own" on public.transactions
  for insert with check (auth.uid() = user_id);

drop policy if exists "transactions_update_own" on public.transactions;
create policy "transactions_update_own" on public.transactions
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "transactions_delete_own" on public.transactions;
create policy "transactions_delete_own" on public.transactions
  for delete using (auth.uid() = user_id);

grant select, insert, update, delete on public.wallets to authenticated;
grant select, insert, update, delete on public.transactions to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- ---------------------------------------------------------------------------
-- Backfill: one wallet per existing user, then one transaction per expense
-- ---------------------------------------------------------------------------

insert into public.wallets (user_id, name, currency)
select distinct
  e.user_id,
  'Main account',
  coalesce(s.currency, 'INR')
from public.expenses e
left join public.user_settings s on s.user_id = e.user_id
where not exists (
  select 1 from public.wallets w where w.user_id = e.user_id
);

insert into public.transactions (
  user_id,
  type,
  name,
  amount,
  category,
  category_id,
  description,
  date,
  wallet_id,
  transfer_wallet_id,
  recurring_expense_id,
  legacy_expense_id,
  created_at
)
select
  e.user_id,
  'expense',
  e.name,
  e.amount,
  coalesce(nullif(btrim(e.category), ''), 'Other'),
  e.category_id,
  coalesce(e.description, ''),
  e.date,
  (
    select w.id
    from public.wallets w
    where w.user_id = e.user_id
    order by w.id
    limit 1
  ),
  null,
  e.recurring_expense_id,
  e.id,
  coalesce(e.created_at, now())
from public.expenses e
where not exists (
  select 1 from public.transactions t where t.legacy_expense_id = e.id
);

commit;

