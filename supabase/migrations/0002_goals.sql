-- SpendWise AI — savings goals (goals + goal_contributions)
--
-- Run once in the Supabase SQL editor, after 0001_money_model.sql. This
-- migration is purely additive: it creates two new tables and never touches
-- wallets, transactions, expenses, budgets, or any existing row.
--
-- Money model:
--   * `goals.starting_amount`  : what the user had already saved before
--                                tracking this goal in SpendWise.
--   * `goal_contributions`     : every deposit made toward the goal after
--                                that. Withdrawals are not modelled; delete a
--                                contribution to correct a mistake.
--   * Saved today = starting_amount + sum(contributions.amount).
--
-- RLS mirrors the money model: every row is scoped to auth.uid(), and a
-- contribution can only point at a goal the same user owns.

begin;

-- ---------------------------------------------------------------------------
-- Goals
-- ---------------------------------------------------------------------------

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 80),
  emoji text not null default '🎯' check (length(emoji) between 1 and 8),
  target_amount numeric(14, 2) not null check (target_amount > 0),
  starting_amount numeric(14, 2) not null default 0
    check (starting_amount >= 0),
  currency text not null default 'INR'
    check (currency in ('INR', 'USD', 'EUR', 'GBP', 'AED', 'SGD')),
  target_date date,
  note text not null default '' check (length(note) <= 280),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists goals_user_name_key
  on public.goals (user_id, lower(name));

create index if not exists goals_user_active_idx
  on public.goals (user_id, is_active);

drop trigger if exists goals_set_updated_at on public.goals;
create trigger goals_set_updated_at
  before update on public.goals
  for each row execute function public.set_updated_at();

alter table public.goals enable row level security;

drop policy if exists "goals_select_own" on public.goals;
create policy "goals_select_own" on public.goals
  for select using (auth.uid() = user_id);

drop policy if exists "goals_insert_own" on public.goals;
create policy "goals_insert_own" on public.goals
  for insert with check (auth.uid() = user_id);

drop policy if exists "goals_update_own" on public.goals;
create policy "goals_update_own" on public.goals
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "goals_delete_own" on public.goals;
create policy "goals_delete_own" on public.goals
  for delete using (auth.uid() = user_id);

-- ---------------------------------------------------------------------------
-- Goal contributions
-- ---------------------------------------------------------------------------

create table if not exists public.goal_contributions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  goal_id bigint not null references public.goals (id) on delete cascade,
  amount numeric(14, 2) not null check (amount > 0),
  date date not null,
  note text not null default '' check (length(note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists goal_contributions_user_goal_idx
  on public.goal_contributions (user_id, goal_id, date desc);

create index if not exists goal_contributions_user_date_idx
  on public.goal_contributions (user_id, date desc);

drop trigger if exists goal_contributions_set_updated_at
  on public.goal_contributions;
create trigger goal_contributions_set_updated_at
  before update on public.goal_contributions
  for each row execute function public.set_updated_at();

alter table public.goal_contributions enable row level security;

drop policy if exists "goal_contributions_select_own" on public.goal_contributions;
create policy "goal_contributions_select_own" on public.goal_contributions
  for select using (auth.uid() = user_id);

-- A contribution must belong to the signed-in user *and* to a goal that the
-- same user owns, so nobody can write into another account's goal.
drop policy if exists "goal_contributions_insert_own" on public.goal_contributions;
create policy "goal_contributions_insert_own" on public.goal_contributions
  for insert with check (
    auth.uid() = user_id
    and exists (
      select 1 from public.goals g
      where g.id = goal_id and g.user_id = auth.uid()
    )
  );

drop policy if exists "goal_contributions_update_own" on public.goal_contributions;
create policy "goal_contributions_update_own" on public.goal_contributions
  for update
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and exists (
      select 1 from public.goals g
      where g.id = goal_id and g.user_id = auth.uid()
    )
  );

drop policy if exists "goal_contributions_delete_own" on public.goal_contributions;
create policy "goal_contributions_delete_own" on public.goal_contributions
  for delete using (auth.uid() = user_id);

grant select, insert, update, delete on public.goals to authenticated;
grant select, insert, update, delete on public.goal_contributions to authenticated;
grant usage, select on all sequences in schema public to authenticated;

commit;

